_ALLOWED = re.compile(r"&lt;(/?)(i|sub|sup)&gt;")
_MDLINK = re.compile(r"\[([^\]]+)\]\((https://[^)\s]+)\)")


def clean(s):
    """Catalogue text is third-party: escape everything, then re-admit only
    <i>, <sub>, <sup> and markdown links to https URLs."""
    s = html.escape(html.unescape(s), quote=True)
    s = _ALLOWED.sub(r"<\1\2>", s)
    s = _MDLINK.sub(r'<a href="\2">\1</a>', s)
    return s


def load():
    cat = json.load(open(os.path.join(HERE, "catalog.json"), encoding="utf-8"))
    scores = {}
    for line in open(os.path.join(HERE, "scores.tsv"), encoding="utf-8"):
        if line.startswith("#") or not line.strip():
            continue
        fid, applied, difficulty, year, note = line.rstrip("\n").split("|")
        scores[fid] = (int(applied), int(difficulty), int(year) if year else None, note)
    assert set(scores) == {f["id"] for f in cat}, "scores.tsv and catalog.json disagree"
    rows = []
    for f in cat:
        a, d, y, note = scores[f["id"]]
        assert 1 <= a <= 5 and 1 <= d <= 5
        rows.append(dict(
            id=f["id"], title=clean(f["title"]), desc=clean(f["desc"]),
            subject=f["subject"],
            lean=2 if f["lean_main"] else 1 if f["lean"] else 0,
            applied=a, difficulty=d, year=y, note=html.escape(note),
            papers=[dict(title=clean(p["title"]), path=p["path"]) for p in f["papers"]],
        ))
    return rows


def write_data(rows):
    js = "// Generated by scripts/build_results.py — do not hand-edit.\n"
    payload = json.dumps(rows, ensure_ascii=False, separators=(",", ":")).replace("</", "<\\/")
    js += "const RESULTS = " + payload + ";\n"
    with open(os.path.join(DOCS, "results-data.js"), "w", encoding="utf-8") as fh:
        fh.write(js)


def crosstab(rows):
    c = collections.Counter((r["applied"], r["difficulty"]) for r in rows)
    out = ['<table class="impl xtab"><thead><tr><th>Applied</th>']
    out += [f"<th>Difficulty {d}</th>" for d in range(1, 6)]
    out.append("<th>All</th></tr></thead><tbody>")
    for a in range(5, 0, -1):
        cells = "".join(f"<td>{c[(a, d)] or '&middot;'}</td>" for d in range(1, 6))
        total = sum(c[(a, d)] for d in range(1, 6))
        out.append(f"<tr><td>{a}</td>{cells}<td>{total}</td></tr>")
    out.append("</tbody></table>")
    return "\n".join(out)


def rubric(labels):
    return "\n".join(f"        <li><em>{k}.</em> {labels[k]}</li>" for k in range(5, 0, -1))


